def test_detection_activity_exists():
    """
    Verify that the final IDS results contain actual
    detection activity.

    Detection activity is determined from the
    ids_detection_method column.

    Examples of valid detection activity:

        ML
        RULE
        ANOMALY
        RULE + ML
        ANOMALY + ML
        RULE + ANOMALY + ML

    NONE is allowed in the dataset, but the complete
    dataset must contain at least one real detection.
    """

    df = load_ids_results()

    # --------------------------------------------------------
    # The final IDS engine records detection activity in
    # ids_detection_method.
    # --------------------------------------------------------

    assert "ids_detection_method" in df.columns, (
        "ids_detection_method column is missing."
    )

    detection_methods = (
        df["ids_detection_method"]
        .dropna()
        .astype(str)
        .str.strip()
        .str.upper()
    )

    assert len(detection_methods) > 0, (
        "No detection methods were recorded."
    )

    # --------------------------------------------------------
    # NONE means no detector triggered for that record.
    # Any other method represents actual detection activity.
    # --------------------------------------------------------

    non_detection_methods = {
        "",
        "NONE",
        "NAN",
        "NULL",
    }

    detected_methods = [
        method
        for method in detection_methods
        if method not in non_detection_methods
    ]

    assert len(detected_methods) > 0, (
        "No detection activity was found in the IDS results."
    )

    print("\nDetection activity found:")
    print(
        pd.Series(detected_methods)
        .value_counts()
    )

    print(
        f"\nRecords with detection activity: "
        f"{len(detected_methods)}"
    )