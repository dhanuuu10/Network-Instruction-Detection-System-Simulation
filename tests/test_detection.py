ROOT_DIR = Path(__file__).resolve().parents[1]

IDS_RESULTS_FILE = ROOT_DIR / "data" / "ids_results.csv"


# ============================================================
# LOAD IDS RESULTS
# ============================================================

def load_ids_results():
    """
    Load the final IDS results generated by ids_engine.py.
    """

    assert IDS_RESULTS_FILE.exists(), (
        f"IDS results file not found: {IDS_RESULTS_FILE}"
    )

    df = pd.read_csv(IDS_RESULTS_FILE)

    assert not df.empty, "IDS results file is empty."

    return df


