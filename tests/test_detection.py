def test_detection_methods():
    """
    Verify that IDS detection methods contain only
    recognized detection sources and valid combinations.

    Valid individual detection sources:
        RULE
        ANOMALY
        ML

    Valid examples:
        NONE
        RULE
        ANOMALY
        ML
        RULE + ANOMALY
        RULE + ML
        ANOMALY + ML
        RULE + ANOMALY + ML
    """

    df = load_ids_results()

    actual_methods = set(
        df["ids_detection_method"]
        .dropna()
        .astype(str)
        .str.strip()
        .unique()
    )

    allowed_sources = {
        "RULE",
        "ANOMALY",
        "ML",
    }

    for method in actual_methods:

        # NONE is valid when no detection source triggered.
        if method == "NONE":
            continue

        parts = {
            part.strip()
            for part in method.split("+")
        }

        unexpected_parts = parts - allowed_sources

        assert not unexpected_parts, (
            f"Unexpected detection method '{method}'. "
            f"Unknown detection source(s): {unexpected_parts}"
        )

        assert len(parts) >= 1, (
            f"Invalid empty detection method: '{method}'"
        )

    print("\nActual detection methods:")
    print(df["ids_detection_method"].value_counts())


